#!/usr/bin/env bash
# Fast static check of the Qt interface QML with qmllint.
#
# usage: qml-check.sh [options] [file.qml|dir ...]
#   no file args      -> lint every QML file of the Qt module
#   file/dir args     -> lint only those (paths relative to cwd or to VLC_SRC)
#   --changed         -> lint QML files changed vs. git HEAD (+ untracked)
#   --all-warnings    -> do not filter warnings (very noisy, see below)
#   --json FILE       -> also write qmllint's raw JSON report to FILE
#   -j N              -> parallel qmllint processes (default: nproc)
#   --show-known      -> also print findings that are in the upstream baseline
#   --update-baseline -> rewrite qmllint-baseline.txt from the current tree
#                        (only do this on an unmodified upstream checkout)
#
# Exit code: 0 if no errors, 1 if errors were found.
#
# How it works: the QML files of modules/gui/qt are packaged in Qt resources
# (VLC/<Module>/res.qrc + qmldir, generated by meson at configure time into
# $VLC_BUILD/modules/gui/qt/VLC/*). qmllint needs them laid out as a real QML
# import tree, so this script mirrors that layout with symlinks into
# $VLC_BUILD/qmllint-tree/VLC/<Module>/ (pointing back into VLC_SRC) and lints
# the files there, translating paths back to source paths in the report.
#
# Filtering: many VLC types (MainCtx, models, Navigation, ColorContext...) are
# registered from C++ at runtime and are invisible to qmllint. Findings about
# names that exist as C++ classes / qmlRegister*() names in modules/gui/qt are
# dropped, as are unqualified-access warnings. Findings already present in
# upstream (qmllint-baseline.txt, matched by file+category+message, not line)
# are hidden. NEW findings are reported as:
#   ERROR    syntax errors, unknown components ("Foo was not found"),
#            duplicate bindings/names, alias/inheritance cycles, read-only
#            writes, bad signal handler params, ... -> exit code 1
#   warning  other qmllint categories (missing properties on QML types,
#            required properties, PropertyChanges style...) -> exit code 0
# qmllint cannot see runtime errors (e.g. a property of a C++ object that
# does not exist); use screenshot.sh, which prints QML runtime warnings.
# A newly added QML file must also be listed in modules/gui/qt/meson.build;
# files not listed there are linted but reported as NOT-IN-MESON warnings.
# Before linting, qt-packaging-check.sh is run (exit code 1 if it fails):
# QML imports outside qml-imports-allowlist.txt (modules missing from the
# Windows static Qt, e.g. QtQuick.Shapes), meson.build vs Makefile.am QML
# lists and assets.qrc/libqt_plugin_la_RES consistency.
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

all_warnings=0
show_known=0
update_baseline=0
BASELINE="$(dirname "${BASH_SOURCE[0]}")/qmllint-baseline.txt"
changed=0
json_out=""
jobs="$(nproc)"
args=()
while [ $# -gt 0 ]; do
    case "$1" in
        --all-warnings) all_warnings=1 ;;
        --changed) changed=1 ;;
        --show-known) show_known=1 ;;
        --update-baseline) update_baseline=1 ;;
        --json) json_out="$2"; shift ;;
        -j) jobs="$2"; shift ;;
        -h|--help) sed -n '2,/^set -e/{/^#/p}' "$0"; exit 0 ;;
        *) args+=("$1") ;;
    esac
    shift
done

# The lint tree only needs the configure-time generated res.qrc/qmldir files.
# If this worktree has no build dir of its own, reuse the main one (source
# paths are rewritten to VLC_SRC below).
if [ ! -d "$VLC_BUILD/modules/gui/qt/VLC" ] && [ -d /home/user/vlc-build/modules/gui/qt/VLC ]; then
    VLC_BUILD=/home/user/vlc-build
fi
[ -d "$VLC_BUILD/modules/gui/qt/VLC" ] || die "no generated QML module dirs in $VLC_BUILD (run setup.sh)"

packaging_status=0
"$(dirname "${BASH_SOURCE[0]}")/qt-packaging-check.sh" || packaging_status=1

QMLLINT="$VLC_QT_DIR/bin/qmllint"
[ -x "$QMLLINT" ] || die "qmllint not found at $QMLLINT"

tree="$VLC_BUILD/qmllint-tree"

# --- build the import tree + the list of files to lint -----------------------
filelist="$(mktemp)"; trap 'rm -f "$filelist" "$filelist".*' EXIT

if [ $changed = 1 ]; then
    ( cd "$VLC_SRC" && { git diff --name-only HEAD -- 'modules/gui/qt/*.qml'; \
                         git ls-files --others --exclude-standard -- 'modules/gui/qt/*.qml'; } ) \
        | sed "s|^|$VLC_SRC/|" > "$filelist.req"
    [ -s "$filelist.req" ] || { echo "qml-check: no changed QML files"; exit $packaging_status; }
else
    : > "$filelist.req"
    for a in "${args[@]+"${args[@]}"}"; do
        if [ -e "$a" ]; then p="$(realpath "$a")"; elif [ -e "$VLC_SRC/$a" ]; then p="$(realpath "$VLC_SRC/$a")"; else die "no such file: $a"; fi
        if [ -d "$p" ]; then find "$p" -name '*.qml' >> "$filelist.req"; else echo "$p" >> "$filelist.req"; fi
    done
fi

python3 -I - "$VLC_BUILD" "$VLC_SRC" "$tree" "$filelist.req" "$filelist" <<'EOF'
import json, os, re, shutil, sys
build, src, tree, reqf, outf = sys.argv[1:6]
info = json.load(open(os.path.join(build, "meson-info", "meson-info.json")))
cfg_src = os.path.realpath(info["directories"]["source"])
src = os.path.realpath(src)
qtdir = os.path.join(build, "modules", "gui", "qt", "VLC")
if os.path.isdir(tree):
    shutil.rmtree(tree)
mapping = {}  # source path -> tree path
for mod in sorted(os.listdir(qtdir)):
    qrc = os.path.join(qtdir, mod, "res.qrc")
    if not os.path.isfile(qrc):
        continue
    dst = os.path.join(tree, "VLC", mod)
    os.makedirs(dst, exist_ok=True)
    for alias, path in re.findall(r'<file alias="([^"]+)">([^<]+)</file>', open(qrc).read()):
        path = os.path.realpath(path)
        if path.startswith(cfg_src + os.sep):
            path = src + path[len(cfg_src):]
        os.symlink(path, os.path.join(dst, alias))
        mapping[path] = os.path.join(dst, alias)
    with open(os.path.join(qtdir, mod, "qmldir")) as f, open(os.path.join(dst, "qmldir"), "w") as o:
        o.writelines(l for l in f if not l.startswith("prefer "))
req = [os.path.realpath(l.strip()) for l in open(reqf) if l.strip()]
if not req:
    req = sorted(mapping)
missing = []
with open(outf, "w") as o:
    for p in req:
        if not p.endswith(".qml") or not os.path.exists(p):
            continue
        if p in mapping:
            o.write(f"{mapping[p]}\t{p}\n")
        else:
            missing.append(p)
            o.write(f"{p}\t{p}\n")
for p in missing:
    print(f"NOT-IN-MESON {os.path.relpath(p, src)}: not listed in modules/gui/qt/meson.build (it will not be packaged)")
json.dump({os.path.realpath(t): s for s, t in mapping.items()}, open(outf + ".map", "w"))
EOF

n="$(wc -l < "$filelist")"
[ "$n" -gt 0 ] || { echo "qml-check: nothing to lint"; exit $packaging_status; }


# --- run qmllint --------------------------------------------------------------
lintopts=(--bare -I "$VLC_QT_DIR/qml" -I "$tree" --json -)
if [ $all_warnings = 0 ]; then
    # Categories that are almost only false positives caused by C++-registered
    # types / context properties qmllint can't see.
    for c in unqualified unused-imports multiline-strings with; do
        lintopts+=("--$c" disable)
    done
fi
help="$("$QMLLINT" --help 2>/dev/null)"
filtered=(); i=0
while [ $i -lt ${#lintopts[@]} ]; do   # drop categories this qmllint doesn't know
    o="${lintopts[$i]}"
    if [[ "$o" == --* ]] && [ "$o" != --bare ] && [ "$o" != --json ] && ! grep -q -- "  $o " <<<"$help"; then
        i=$((i+2)); continue
    fi
    filtered+=("$o"); i=$((i+1))
done

cut -f1 "$filelist" | (cd "$tree" && xargs -d '\n' -P "$jobs" -n 16 \
    sh -c '"$0" "$@" 2>/dev/null; true' "$QMLLINT" "${filtered[@]}") > "$filelist.json"

lint_status=0
python3 -I - "$filelist.json" "$filelist.map" "$VLC_SRC" "$all_warnings" "$show_known" \
    "$update_baseline" "$BASELINE" "${json_out:-}" <<'EOF' || lint_status=$?
import collections, json, os, re, sys
raw, mapf, src, all_warn, show_known, update, basef, json_out = sys.argv[1:9]
all_warn, show_known, update = all_warn == "1", show_known == "1", update == "1"
mp = json.load(open(mapf))

# Names of types registered from C++ (qmllint can't see them).
cxx, cxxprops = set(), set()
qtsrc = os.path.join(src, "modules", "gui", "qt")
for d, _, fs in os.walk(qtsrc):
    for f in fs:
        if f.endswith((".cpp", ".hpp", ".h")):
            t = open(os.path.join(d, f), errors="replace").read()
            cxx |= set(re.findall(r"\b(?:class|struct)\s+(\w+)", t))
            cxx |= set(re.findall(r"QML_NAMED_ELEMENT\(\s*(\w+)", t))
            for st in re.findall(r"qmlRegister\w*[^;]*;", t, re.S):
                cxx |= set(re.findall(r'"([A-Z]\w*)"', st))
            cxxprops.update(re.findall(r"Q_PROPERTY\(\s*[\w:<>, *]+?[\s*&]+(\w+)\s+(?:READ|MEMBER|WRITE|BINDABLE)", t))
            cxxprops.update(re.findall(r"VLC_QT_\w*PROPERTY\w*\(\s*[^,]+,\s*(\w+)", t))

def is_cxx_noise(cat, msg):
    m = (re.match(r"(\S+) was not found\. Did you add all imports", msg)
         or re.match(r"Type (\S+) is used but it is not resolved", msg))
    if m:
        return m.group(1).split(".")[-1] in cxx
    m = re.match(r'Could not find property "(\w+)"', msg)
    if m:
        return m.group(1) in cxxprops
    m = re.match(r'Member "(\w+)" not found on type "(\w+)"', msg)
    if m:
        return (m.group(1) in cxxprops or m.group(1) in cxx or m.group(2) in cxx
                or m.group(2).startswith("Q") or m.group(2) == "undefined")
    if cat in ("unresolved-type", "missing-type", "incompatible-type",
               "unresolved-alias", "import"):
        # property/alias/member typing fallout of unresolved C++ types
        return not msg.startswith(("Type warnings occurred", "Failed to import"))
    return False

# Hard failures (exit 1). Everything else new is a WARNING.
HARD = {"syntax", "import", "unresolved-type", "duplicate-property-binding",
        "duplicated-name", "alias-cycle", "inheritance-cycle",
        "read-only-property", "signal-handler-parameters", "non-list-property",
        "invalid-lint-directive", "var-used-before-declaration"}

dec = json.JSONDecoder()
text = open(raw).read()
reports, i = [], 0
while i < len(text):
    while i < len(text) and text[i].isspace():
        i += 1
    if i >= len(text):
        break
    obj, i = dec.raw_decode(text, i)
    reports.extend(obj.get("files", []))
if json_out:
    json.dump({"files": reports}, open(json_out, "w"), indent=1)

findings = []  # (rel, line, col, cat, msg, hint)
for f in reports:
    fn = os.path.realpath(f.get("filename", "?"))
    rel = os.path.relpath(mp.get(fn, fn), src)
    ws = f.get("warnings", [])
    for w in ws:
        if w.get("type") == "info":
            continue
        cat, msg = w.get("id", "") or "unknown", w.get("message", "").strip()
        if not all_warn and is_cxx_noise(cat, msg):
            continue
        sugs = w.get("suggestions") or ([w["suggestion"]] if w.get("suggestion") else [])
        hint = "; ".join(s.get("message", "") for s in sugs if s.get("message"))
        findings.append((rel, w.get("line", 0), w.get("column", 0), cat, msg, hint))
    if not f.get("success", True) and not ws:
        findings.append((rel, 0, 0, "syntax", "qmllint failed on this file", ""))

key = lambda x: f"{x[0]}\t{x[3]}\t{x[4]}"
if update:
    c = collections.Counter(key(x) for x in findings if x[3] != "syntax")
    with open(basef, "w") as o:
        o.write("# qmllint findings already present upstream; generated by qml-check.sh --update-baseline\n")
        for k in sorted(c):
            o.write(f"{c[k]}\t{k}\n")
    print(f"qml-check: wrote {sum(c.values())} baseline entries to {basef}", file=sys.stderr)
    sys.exit(0)

base = collections.Counter()
if not all_warn and os.path.exists(basef):
    for l in open(basef):
        if l.startswith("#") or not l.strip():
            continue
        n, k = l.rstrip("\n").split("\t", 1)
        base[k] += int(n)

errors = warnings = known = 0
for x in sorted(findings, key=lambda x: (x[0], x[1], x[2])):
    k = key(x)
    if base[k] > 0:
        base[k] -= 1
        known += 1
        if not show_known:
            continue
        kind = "known"
    elif x[3] in HARD or all_warn:
        kind = "ERROR"; errors += 1
    else:
        kind = "warning"; warnings += 1
    print(f"{x[0]}:{x[1]}:{x[2]}: {kind}: {x[4]} [{x[3]}]")
    if x[5]:
        print(f"    hint: {x[5]}")
sys.stdout.flush()
print(f"qml-check: {len(reports)} file(s): {errors} error(s), {warnings} new warning(s), "
      f"{known} known upstream issue(s) hidden", file=sys.stderr)
sys.exit(1 if errors else 0)
EOF

if [ $packaging_status != 0 ]; then
    echo "qml-check: qt-packaging-check.sh failed (see PACKAGING lines above)" >&2
    exit 1
fi
exit $lint_status
